#include <iostream>
using namespace std;

int main()
{
	//转义字符

	//换行符 \n
	
	cout << "Hello World\n";

	//反斜杠 \\

	cout << "\\\\\\" << endl;

	//水平制表符 \t
	//水平制表符添加处和前面的字符一共占八个空间
	cout << "aaa\tHelloWorld" << endl;
	cout << "aaaaaaa\tHelloWorld" << endl;
	cout << "aaaaaaaa\tHelloWorld" << endl;
	cout << "aaaaaaaaaaaa\tHelloWorld" << endl;
	cout << "\tHelloWorld" << endl;








	system("pause");
	return 0;
}